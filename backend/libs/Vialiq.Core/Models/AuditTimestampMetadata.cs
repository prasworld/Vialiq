namespace Vialiq.Core.Models;

using System;

/// <summary>
/// Encapsulates regulatory Part 11 timestamp authority and monotonic causal ordering.
/// Conforms to FDA 21 CFR Part 11 § 11.10(a),(e) and EU Annex 11 § 9.
/// </summary>
/// <param name="ServerTimestampUtc">Authoritative database commit timestamp ($$NOW) generated inside the ACID transaction.</param>
/// <param name="AuditSequence">Monotonically incrementing integer sequence (1, 2, 3...) strictly ordered per study.</param>
/// <param name="ClientReportedLocalTime">Optional client-reported local time for reference display in UI.</param>
/// <param name="ClientTimeZoneId">Optional client-reported IANA or Windows timezone identifier.</param>
public sealed record AuditTimestampMetadata(
    DateTime ServerTimestampUtc,
    long AuditSequence,
    DateTime? ClientReportedLocalTime = null,
    string? ClientTimeZoneId = null)
{
    /// <summary>
    /// Constructs regulatory metadata using the authoritative database commit timestamp 
    /// generated by the primary replica set node inside the ACID transaction.
    /// Application clock DateTime.UtcNow is strictly prohibited to prevent distributed clock skew inversion.
    /// </summary>
    /// <param name="databaseCommitTimestampUtc">The authoritative UTC database commit timestamp.</param>
    /// <param name="auditSequence">The monotonically increasing audit sequence counter.</param>
    /// <param name="clientLocalTime">Optional client reported local time for reference.</param>
    /// <param name="clientTimeZoneId">Optional client reported timezone ID.</param>
    /// <returns>A new <see cref="AuditTimestampMetadata"/> instance normalized to UTC.</returns>
    public static AuditTimestampMetadata FromDatabaseCommit(
        DateTime databaseCommitTimestampUtc,
        long auditSequence,
        DateTime? clientLocalTime = null,
        string? clientTimeZoneId = null)
    {
        if (databaseCommitTimestampUtc.Kind == DateTimeKind.Local)
        {
            databaseCommitTimestampUtc = databaseCommitTimestampUtc.ToUniversalTime();
        }
        else if (databaseCommitTimestampUtc.Kind == DateTimeKind.Unspecified)
        {
            databaseCommitTimestampUtc = DateTime.SpecifyKind(databaseCommitTimestampUtc, DateTimeKind.Utc);
        }

        return new AuditTimestampMetadata(
            ServerTimestampUtc: databaseCommitTimestampUtc,
            AuditSequence: auditSequence,
            ClientReportedLocalTime: clientLocalTime,
            ClientTimeZoneId: clientTimeZoneId);
    }
}
